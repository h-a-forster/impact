// Planted faults: put known bugs into a copy of each PR commit and see what catches them.
// It measures the review system itself: do the faults that slip past the tests sit where the
// map said "Unverified"?   Run with:  npm run planted
import fs from "node:fs";
import path from "node:path";
import { snapshotWithFault } from "../src/lib/sample.mjs";
import { runIn } from "../src/lib/runner.mjs";
import { buildModel, loadRevisions } from "../src/lib/model.mjs";
import { DATA, ROOT } from "../src/lib/paths.mjs";

const spec = JSON.parse(fs.readFileSync(path.join(ROOT, "planted", "req-17.faults.json"), "utf8"));
const revisions = loadRevisions();
const pr = revisions.prs.find((p) => p.id === spec.pr);
const short = (s) => s.slice(0, 7);

const results = { pr: spec.pr, generatedBy: "node scripts/planted.mjs (rule-based; no model is called)", ranAt: new Date().toISOString(), commits: [] };
for (const c of pr.commits) {
  const model = buildModel(revisions, pr.id, c.sha);
  const flagOf = (nodeId) => {
    const ev = model.evidence.find((e) => e.nodeId === nodeId);
    return ev ? ev.status : "not-affected";
  };
  const faults = [];
  for (const fault of spec.faults) {
    const { dir, applied } = snapshotWithFault(c.sha, fault);
    if (!applied) {
      faults.push({ id: fault.id, node: fault.node, what: fault.what, applied: false, mapFlag: flagOf(fault.node) });
      continue;
    }
    const run = runIn(dir, `fault-${fault.id}`);
    fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5 });
    const failing = run.tests.filter((t) => t.status === "failed").map((t) => t.name);
    faults.push({
      id: fault.id, node: fault.node, what: fault.what, applied: true,
      caughtByTests: failing.length > 0, failingTests: failing,
      mapFlag: flagOf(fault.node), // what the map said about this function BEFORE the fault was planted
    });
  }
  const applied = faults.filter((f) => f.applied);
  const escaped = applied.filter((f) => !f.caughtByTests);
  const summary = {
    planted: applied.length,
    caughtByTests: applied.length - escaped.length,
    escapedTests: escaped.length,
    // The map earns trust when escapes sit where it warned, and loses it when they sit where it said "supported".
    escapedWhereMapSaidUnverified: escaped.filter((f) => f.mapFlag === "unverified").map((f) => f.id),
    escapedWhereMapSaidSupported: escaped.filter((f) => f.mapFlag === "supported").map((f) => f.id),
    escapedOutsideThePr: escaped.filter((f) => f.mapFlag === "not-affected").map((f) => f.id),
  };
  results.commits.push({ sha: c.sha, index: c.index, route: model.classifier2.route, summary, faults });
  console.log(`commit ${c.index} ${short(c.sha)}: planted ${summary.planted}, tests caught ${summary.caughtByTests}, escaped ${summary.escapedTests}` +
    ` (map said unverified: ${summary.escapedWhereMapSaidUnverified.join(",") || "-"}; map said supported: ${summary.escapedWhereMapSaidSupported.join(",") || "-"}; outside the PR: ${summary.escapedOutsideThePr.join(",") || "-"})`);
}
fs.mkdirSync(path.join(DATA, "planted"), { recursive: true });
fs.writeFileSync(path.join(DATA, "planted", `${spec.pr}.json`), JSON.stringify(results, null, 2) + "\n");

// ---- docs/measurement.md (generated) ----
const row = (f) => `| ${f.id} | ${f.what} | \`${f.node.split("#")[1]}()\` | ${f.mapFlag} | ${f.caughtByTests ? "caught (" + f.failingTests.length + " test)" : "**escaped**"} |`;
const md = [
  "# Measurement: planted faults",
  "",
  "Generated by `npm run planted` from `planted/req-17.faults.json`. Do not edit.",
  "",
  "Green tests say the code passed the tests that exist. They do not say the tests would notice a bug.",
  "So we plant known bugs into a copy of each PR commit, run the same suite, and compare the result",
  "with what the Impact Map said about that function **before** the bug was planted.",
  "The method comes from the teammate project Impact Ledger. No model is called.",
  "",
  ...results.commits.flatMap((c) => [
    `## PR commit ${c.index} (\`${short(c.sha)}\`) · route: ${c.route}`,
    "",
    `Planted ${c.summary.planted}. The tests caught ${c.summary.caughtByTests}. ${c.summary.escapedTests} got past the tests.`,
    "",
    `- Escaped where the map said **Unverified**: ${c.summary.escapedWhereMapSaidUnverified.join(", ") || "none"}. The map warned about these.`,
    `- Escaped where the map said **Supported**: ${c.summary.escapedWhereMapSaidSupported.join(", ") || "none"}. These are misses of the map's evidence rule.`,
    `- Escaped in code the PR does not touch or reach: ${c.summary.escapedOutsideThePr.join(", ") || "none"}. The map makes no claim there.`,
    "",
    "| Fault | What was planted | Function | Map said (before planting) | Tests |",
    "|---|---|---|---|---|",
    ...c.faults.filter((f) => f.applied).map(row),
    "",
  ]),
  "## What this shows, and what it does not",
  "",
  "- On commit 1 the suite is green, and the faults planted in Order Import get past it. The map had marked that function Unverified. That is the gap the walkthrough is about, measured instead of argued.",
  "- On commit 2 the new Order Import test catches the same faults. The targeted check closed the gap.",
  "- A fault that escapes where the map said Supported is a real miss: \"Supported for the tested case\" covers the tested case only. Each such miss should become a review eval.",
  "- This is one small synthetic repo and a handful of hand-written faults. It is a sample observation, not an accuracy figure.",
  "- For the real Tieto PRs, the Impact Ledger project ran its own planted-fault study. Its result is shown in the app under Track record and is not re-run here.",
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "docs", "measurement.md"), md);
console.log("Wrote data/planted/req-17.json and docs/measurement.md");
